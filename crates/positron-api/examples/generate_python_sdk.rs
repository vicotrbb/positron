//! Emit the Python package from the canonical Public Interface metadata.
mod sdk_metadata;
use serde_json::{Value, json};
use std::{error::Error, fmt::Write, fs, path::Path};
type Result<T> = std::result::Result<T, Box<dyn Error>>;
fn python_type(schema: &Value) -> String {
    if let Some(values) = schema["enum"].as_array() {
        return format!(
            "Literal[{}]",
            values
                .iter()
                .map(Value::to_string)
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    if let Some(value) = schema.get("const") {
        return format!("Literal[{value}]");
    }
    if let Some(reference) = schema["$ref"].as_str() {
        return reference.rsplit('/').next().unwrap_or("Any").into();
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(variants) = schema[key].as_array() {
            return variants
                .iter()
                .map(python_type)
                .collect::<Vec<_>>()
                .join(" | ");
        }
    }
    match schema["type"].as_str() {
        Some("string") => "str".into(),
        Some("boolean") => "bool".into(),
        Some("integer") => "int".into(),
        Some("number") => "float".into(),
        Some("array") => format!("list[{}]", python_type(&schema["items"])),
        Some("null") => "None".into(),
        _ => "dict[str, Any]".into(),
    }
}
fn main() -> Result<()> {
    let owner = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = owner.parent().and_then(Path::parent).ok_or("root")?;
    let output = std::env::args_os()
        .nth(1)
        .ok_or("usage: generate_python_sdk OUTPUT")?;
    let output = Path::new(&output);
    let package = output.join("positron_sdk");
    fs::create_dir_all(package.join("api"))?;
    fs::create_dir_all(output.join("examples"))?;
    let sdk_metadata::Contract {
        http,
        openapi,
        descriptor,
        digest,
        errors,
    } = sdk_metadata::contract(root)?;
    let schemas = openapi["components"]["schemas"]
        .as_object()
        .ok_or("schemas")?;
    let mut types = String::from(
        "# Generated by positron-api; do not edit.\nfrom __future__ import annotations\nfrom typing import Any, TypedDict, Required, Literal\n\n",
    );
    for (name, schema) in schemas {
        if let Some(properties) = schema["properties"].as_object() {
            writeln!(types, "{name} = TypedDict({name:?}, {{")?;

            for (field, schema_field) in properties {
                let mut shape = python_type(schema_field);
                if schema_field["nullable"] == true {
                    shape.push_str(" | None");
                }
                if schema["required"]
                    .as_array()
                    .is_some_and(|fields| fields.iter().any(|value| value == field))
                {
                    shape = format!("Required[{shape}]");
                }
                writeln!(types, "    {field:?}: {shape:?},")?;
            }
            types.push_str("}, total=False)\n");
        } else {
            writeln!(types, "{name} = {}", python_type(schema))?;
        }
        types.push('\n');
    }
    fs::write(package.join("types.py"), format!("{}\n", types.trim_end()))?;
    let mut methods = String::new();
    for route in http["mappings"].as_array().ok_or("routes")? {
        let rpc = route["rpc"].as_str().ok_or("rpc")?;
        let (service, method) = rpc
            .strip_prefix("positron.v1.")
            .and_then(|rpc| rpc.split_once('/'))
            .ok_or("rpc")?;
        let name = format!(
            "{}{method}",
            service.strip_suffix("Service").ok_or("service")?
        );
        let mut snake = String::new();
        for (index, character) in name.chars().enumerate() {
            if character.is_uppercase() && index > 0 {
                snake.push('_');
            }
            snake.push(character.to_ascii_lowercase());
        }
        let input = route["request"].as_str().ok_or("request")?;
        let result = route["response"].as_str().ok_or("response")?;
        writeln!(
            methods,
            "    def {snake}(self, request: types.{input}, *, bearer: str | None = None, timeout: float = 5.0) -> types.{result}:\n        return self.call({rpc:?}, request, bearer=bearer, timeout=timeout)\n"
        )?;
    }
    for file in ["codec.py", "errors.py", "query.py", "__init__.py"] {
        fs::copy(owner.join("python").join(file), package.join(file))?;
    }
    let client = fs::read_to_string(owner.join("python/client.py"))?
        .replace("# GENERATED_METHODS", &methods);
    fs::write(
        package.join("client.py"),
        format!("{}\n", client.trim_end()),
    )?;
    fs::write(
        package.join("contract.json"),
        serde_json::to_vec(
            &json!({"api_version":"positron.v1", "schema_digest":digest,"schemas":schemas,"descriptor":descriptor,"routes":http["mappings"],"query_errors":errors}),
        )?,
    )?;
    fs::write(package.join("py.typed"), "")?;
    fs::write(
        package.join("release.json"),
        serde_json::to_vec_pretty(
            &json!({"name":"positron-sdk", "version":env!("CARGO_PKG_VERSION"),"api_version":"positron.v1","schema_digest":digest,"release_manifest_surface":"SdkPython","registry":"https://pypi.org","generator":"positron-api=1,python=3.11,protoc-bin-vendored=3.2.0"}),
        )?,
    )?;
    for file in [
        "positron.proto",
        "schema.sha256",
        "http.json",
        "openapi.json",
        "query-golden-fixtures.json",
        "query-error-fixtures.json",
        "validation-fixtures.json",
    ] {
        fs::copy(
            root.join("api/positron/v1").join(file),
            package.join("api").join(file),
        )?;
    }
    fs::copy(root.join("sdk/python.md"), output.join("README.md"))?;
    fs::copy(root.join("LICENSE"), output.join("LICENSE"))?;
    fs::copy(
        owner.join("python/example.py"),
        output.join("examples/query.py"),
    )?;
    fs::write(
        output.join("pyproject.toml"),
        format!(
            "[build-system]\nrequires = [\"setuptools==80.9.0\"]\nbuild-backend = \"setuptools.build_meta\"\n\n[project]\nname = \"positron-sdk\"\nversion = {:?}\ndescription = \"Generated typed client for the Positron v1 public API\"\nreadme = \"README.md\"\nrequires-python = \">=3.11\"\nlicense = {:?}\ndependencies = []\n\n[tool.setuptools]\npackages = [\"positron_sdk\"]\n\n[tool.setuptools.package-data]\npositron_sdk = [\"py.typed\", \"*.json\", \"api/*\"]\n",
            env!("CARGO_PKG_VERSION"),
            env!("CARGO_PKG_LICENSE")
        ),
    )?;
    fs::write(
        output.join(".gitignore"),
        "__pycache__/\n*.egg-info/\nbuild/\ndist/\n.venv/\n",
    )?;
    Ok(())
}
