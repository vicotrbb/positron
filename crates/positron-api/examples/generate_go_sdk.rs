//! Generate the Go module from canonical Public Interface metadata.
mod sdk_metadata;
use serde_json::{Value, json};
use std::{error::Error, fmt::Write, fs, path::Path};
type Result<T> = std::result::Result<T, Box<dyn Error>>;
fn exported(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut chars = part.chars();
            format!(
                "{}{}",
                chars
                    .next()
                    .map(|c| c.to_ascii_uppercase())
                    .unwrap_or_default(),
                chars.as_str()
            )
        })
        .collect()
}
fn shape(schema: &Value) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        return reference
            .rsplit('/')
            .next()
            .unwrap_or("json.RawMessage")
            .into();
    }
    match schema["type"].as_str() {
        Some("string") => "string".into(),
        Some("boolean") => "bool".into(),
        Some("integer") if schema["format"] == "uint64-json" => "uint64".into(),
        Some("integer") => "int64".into(),
        Some("number") => "float64".into(),
        Some("array") => format!("[]{}", shape(&schema["items"])),
        _ => "json.RawMessage".into(),
    }
}
fn main() -> Result<()> {
    let owner = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = owner.parent().and_then(Path::parent).ok_or("root")?;
    let argument = std::env::args_os()
        .nth(1)
        .ok_or("usage: generate_go_sdk OUTPUT")?;
    let output = Path::new(&argument);
    fs::create_dir_all(output.join("api"))?;
    fs::create_dir_all(output.join("examples/query"))?;
    let sdk_metadata::Contract {
        http,
        openapi,
        descriptor,
        digest,
        errors,
    } = sdk_metadata::contract(root)?;
    let schemas = openapi["components"]["schemas"]
        .as_object()
        .ok_or("schemas")?;
    let mut types = String::from(
        "// Code generated by positron-api. DO NOT EDIT.\npackage positron\n\nimport \"encoding/json\"\n\n",
    );
    writeln!(
        types,
        "const APIVersion = \"positron.v1\"\nconst SchemaDigest = {digest:?}\n"
    )?;
    for (name, schema) in schemas {
        if let Some(properties) = schema["properties"].as_object() {
            writeln!(types, "type {name} struct {{")?;
            for (field, value) in properties {
                let mut kind = shape(value);
                let required = schema["required"]
                    .as_array()
                    .is_some_and(|fields| fields.iter().any(|item| item == field));
                if !required && !kind.starts_with("[]") && kind != "json.RawMessage" {
                    kind = format!("*{kind}");
                }
                writeln!(
                    types,
                    "\t{} {} `json:\"{}{}\"`",
                    exported(field),
                    kind,
                    field,
                    if required { "" } else { ",omitempty" }
                )?;
            }
            types.push_str("}\n\n");
        } else {
            writeln!(types, "type {name} = {}\n", shape(schema))?;
        }
    }
    fs::write(output.join("types.go"), types)?;
    let mut methods = String::new();
    for route in http["mappings"].as_array().ok_or("routes")? {
        let rpc = route["rpc"].as_str().ok_or("rpc")?;
        let (service, method) = rpc
            .strip_prefix("positron.v1.")
            .and_then(|value| value.split_once('/'))
            .ok_or("rpc")?;
        let name = format!(
            "{}{method}",
            service.strip_suffix("Service").ok_or("service")?
        );
        let request = route["request"].as_str().ok_or("request")?;
        let response = route["response"].as_str().ok_or("response")?;
        writeln!(
            methods,
            "func (c *Client) {name}(ctx context.Context, request {request}, bearer string) ({response}, error) {{\n var result {response}\n err := c.Call(ctx, {rpc:?}, request, bearer, &result)\n return result, err\n}}\n"
        )?;
    }
    fs::write(
        output.join("methods.go"),
        format!(
            "// Code generated by positron-api. DO NOT EDIT.\npackage positron\nimport \"context\"\n{methods}"
        ),
    )?;
    fs::write(
        output.join("contract.json"),
        serde_json::to_vec(
            &json!({"api_version":"positron.v1","schema_digest":digest,"schemas":schemas,"descriptor":descriptor,"routes":http["mappings"],"query_errors":errors}),
        )?,
    )?;
    fs::write(
        output.join("release.json"),
        serde_json::to_vec_pretty(
            &json!({"module":"github.com/vicotrbb/positron/sdk/go","version":env!("CARGO_PKG_VERSION"),"api_version":"positron.v1","schema_digest":digest,"release_manifest_surface":"SdkGo","registry":"https://proxy.golang.org","generator":"positron-api=1,go=1.24.0,protoc-bin-vendored=3.2.0"}),
        )?,
    )?;
    fs::write(
        output.join("go.mod"),
        "module github.com/vicotrbb/positron/sdk/go\n\ngo 1.24.0\n",
    )?;
    for file in ["codec.go", "client.go", "query.go"] {
        fs::copy(owner.join("go").join(file), output.join(file))?;
    }
    for file in [
        "positron.proto",
        "schema.sha256",
        "http.json",
        "openapi.json",
        "query-golden-fixtures.json",
        "query-error-fixtures.json",
        "validation-fixtures.json",
    ] {
        fs::copy(
            root.join("api/positron/v1").join(file),
            output.join("api").join(file),
        )?;
    }
    fs::copy(root.join("sdk/go.md"), output.join("README.md"))?;
    fs::copy(root.join("LICENSE"), output.join("LICENSE"))?;
    fs::copy(
        owner.join("go/example.go"),
        output.join("examples/query/main.go"),
    )?;
    let status = std::process::Command::new("gofmt")
        .arg("-w")
        .arg(output)
        .status()?;
    if !status.success() {
        return Err("gofmt failed".into());
    }
    Ok(())
}
