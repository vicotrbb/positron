//! Generate the .NET package from the canonical Public Interface.
mod sdk_metadata;
use serde_json::{Value, json};
use std::{error::Error, fmt::Write, fs, path::Path};
type Result<T> = std::result::Result<T, Box<dyn Error>>;
fn shape(schema: &Value, schemas: &serde_json::Map<String, Value>) -> String {
    if let Some(name) = schema["$ref"].as_str().and_then(|s| s.rsplit('/').next()) {
        return if schemas[name]["properties"].is_object() {
            format!("Types.{name}")
        } else {
            shape(&schemas[name], schemas)
        };
    }
    match schema["type"].as_str() {
        Some("string") => "string".into(),
        Some("boolean") => "bool?".into(),
        Some("integer") if schema["format"] == "uint64-json" => "ulong?".into(),
        Some("integer") => "long?".into(),
        Some("number") => "double?".into(),
        Some("array") => format!(
            "System.Collections.Generic.List<{}>",
            shape(&schema["items"], schemas)
        ),
        _ => "System.Text.Json.Nodes.JsonNode".into(),
    }
}
fn main() -> Result<()> {
    let owner = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = owner.parent().and_then(Path::parent).ok_or("root")?;
    let arg = std::env::args_os()
        .nth(1)
        .ok_or("usage: generate_dotnet_sdk OUTPUT")?;
    let output = Path::new(&arg);
    fs::create_dir_all(output.join("api"))?;
    let sdk_metadata::Contract {
        http,
        openapi,
        descriptor,
        digest,
        errors,
    } = sdk_metadata::contract(root)?;
    let schemas = openapi["components"]["schemas"]
        .as_object()
        .ok_or("schemas")?;
    let mut types = String::from(
        "// Generated by positron-api. DO NOT EDIT.\nnamespace Positron;\npublic static class Types {\n",
    );
    for (name, schema) in schemas {
        if let Some(fields) = schema["properties"].as_object() {
            writeln!(types, " public sealed record {name} {{")?;
            for (name, schema) in fields {
                let mut chars = name.chars();
                let property = format!(
                    "{}{}",
                    chars.next().ok_or("field")?.to_ascii_uppercase(),
                    chars.as_str()
                );
                writeln!(
                    types,
                    "  [System.Text.Json.Serialization.JsonPropertyName({name:?})] public {} {property} {{ get; init; }}",
                    shape(schema, schemas)
                )?;
            }
            types.push_str(" }\n");
        }
    }
    types.push_str("}\n");
    fs::write(output.join("Types.cs"), types)?;
    let mut methods = String::new();
    for route in http["mappings"].as_array().ok_or("routes")? {
        let rpc = route["rpc"].as_str().ok_or("rpc")?;
        let (service, method) = rpc
            .strip_prefix("positron.v1.")
            .and_then(|v| v.split_once('/'))
            .ok_or("rpc")?;
        let service = service.strip_suffix("Service").ok_or("service")?;
        let request = route["request"].as_str().ok_or("request")?;
        let response = route["response"].as_str().ok_or("response")?;
        writeln!(
            methods,
            " public async System.Threading.Tasks.Task<Types.{response}> {service}{method}Async(Types.{request} request, string bearer = null, System.TimeSpan? timeout = null, System.Threading.CancellationToken cancellation = default) => Codec.Convert<Types.{response}>(await CallAsync({rpc:?}, request, bearer, timeout, cancellation).ConfigureAwait(false));"
        )?;
    }
    for file in [
        "Codec.cs",
        "Query.cs",
        "BatchTracker.cs",
        "PositronException.cs",
        "Client.cs",
    ] {
        let content = fs::read_to_string(owner.join("dotnet").join(file))?
            .replace("// GENERATED_METHODS", &methods);
        fs::write(output.join(file), content)?;
    }
    fs::write(
        output.join("contract.json"),
        serde_json::to_vec(
            &json!({"api_version":"positron.v1","schema_digest":digest,"schemas":schemas,"descriptor":descriptor,"routes":http["mappings"],"query_errors":errors}),
        )?,
    )?;
    fs::write(
        output.join("release.json"),
        serde_json::to_vec_pretty(
            &json!({"name":"Positron.SDK","version":env!("CARGO_PKG_VERSION"),"api_version":"positron.v1","schema_digest":digest,"release_manifest_surface":"SdkDotNet","registry":"https://api.nuget.org/v3/index.json","generator":"positron-api=1,dotnet=8.0.427,protoc-bin-vendored=3.2.0"}),
        )?,
    )?;
    for file in [
        "positron.proto",
        "schema.sha256",
        "http.json",
        "openapi.json",
        "query-golden-fixtures.json",
        "query-error-fixtures.json",
        "validation-fixtures.json",
    ] {
        fs::copy(
            root.join("api/positron/v1").join(file),
            output.join("api").join(file),
        )?;
    }
    fs::copy(owner.join("dotnet/pack.py"), output.join("pack.py"))?;
    fs::copy(root.join("LICENSE"), output.join("LICENSE"))?;
    fs::copy(root.join("sdk/dotnet.md"), output.join("README.md"))?;
    fs::write(
        output.join("Positron.SDK.csproj"),
        fs::read_to_string(owner.join("dotnet/Positron.SDK.csproj"))?
            .replace("@VERSION@", env!("CARGO_PKG_VERSION")),
    )?;
    fs::write(
        output.join("global.json"),
        "{\"sdk\":{\"version\":\"8.0.427\",\"rollForward\":\"disable\"}}\n",
    )?;
    fs::write(
        output.join("toolchain.json"),
        serde_json::to_vec_pretty(
            &json!({"sdk":"8.0.427","framework":"net8.0","linux_x64_url":"https://builds.dotnet.microsoft.com/dotnet/Sdk/8.0.427/dotnet-sdk-8.0.427-linux-x64.tar.gz","linux_x64_sha512":"85725692f465f5024b9b42a159a29d9f73e8c57ad9e8bfe1e7028a505d18031d68931e8aa3f9de44145b08170dde897c8a78e1aa18d4219698b6891af7095d39","osx_arm64_url":"https://builds.dotnet.microsoft.com/dotnet/Sdk/8.0.427/dotnet-sdk-8.0.427-osx-arm64.tar.gz","osx_arm64_sha512":"79786b93f249d233b15f1d6338d4798bd71c8143f267c5e84de76c9eb8a1054920e56ea5478f7bddfb74b951cc58aaca11fbd780cf134350b7cb7cdcb42a8c8c"}),
        )?,
    )?;
    fs::write(output.join(".gitignore"), "bin/\nobj/\n")?;
    Ok(())
}
