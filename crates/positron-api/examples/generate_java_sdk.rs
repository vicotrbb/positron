//! Generate the JVM package from canonical Public Interface metadata.
mod sdk_metadata;
use serde_json::{Value, json};
use std::{error::Error, fmt::Write, fs, path::Path};
type Result<T> = std::result::Result<T, Box<dyn Error>>;
fn shape(schema: &Value, schemas: &serde_json::Map<String, Value>) -> String {
    if let Some(reference) = schema["$ref"].as_str().and_then(|v| v.rsplit('/').next()) {
        return if schemas[reference]["properties"].is_object() {
            format!("Types.{reference}")
        } else {
            shape(&schemas[reference], schemas)
        };
    }
    match schema["type"].as_str() {
        Some("string") => "String".into(),
        Some("boolean") => "Boolean".into(),
        Some("integer") => "java.math.BigInteger".into(),
        Some("number") => "Double".into(),
        Some("array") => format!("java.util.List<{}>", shape(&schema["items"], schemas)),
        _ => "com.fasterxml.jackson.databind.JsonNode".into(),
    }
}
fn main() -> Result<()> {
    let owner = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = owner.parent().and_then(Path::parent).ok_or("root")?;
    let argument = std::env::args_os()
        .nth(1)
        .ok_or("usage: generate_java_sdk OUTPUT")?;
    let output = Path::new(&argument);
    let java = output.join("src/main/java/dev/positron");
    let resources = output.join("src/main/resources/dev/positron");
    fs::create_dir_all(&java)?;
    fs::create_dir_all(resources.join("api"))?;
    let sdk_metadata::Contract {
        http,
        openapi,
        descriptor,
        digest,
        errors,
    } = sdk_metadata::contract(root)?;
    let schemas = openapi["components"]["schemas"]
        .as_object()
        .ok_or("schemas")?;
    let mut types = String::from(
        "// Generated by positron-api. DO NOT EDIT.\npackage dev.positron;\npublic final class Types {\n private Types() {}\n",
    );
    for (name, schema) in schemas {
        if let Some(properties) = schema["properties"].as_object() {
            writeln!(types, " public record {name}(")?;
            for (index, (field, value)) in properties.iter().enumerate() {
                let identifier = if matches!(
                    field.as_str(),
                    "default"
                        | "public"
                        | "private"
                        | "class"
                        | "native"
                        | "package"
                        | "enum"
                        | "new"
                        | "switch"
                        | "case"
                        | "return"
                        | "void"
                ) {
                    format!("{field}_")
                } else {
                    field.clone()
                };
                writeln!(
                    types,
                    "  @com.fasterxml.jackson.annotation.JsonProperty({field:?}) {} {identifier}{}",
                    shape(value, schemas),
                    if index + 1 == properties.len() {
                        ""
                    } else {
                        ","
                    }
                )?;
            }
            types.push_str(" ) {}\n");
        }
    }
    types.push_str("}\n");
    fs::write(java.join("Types.java"), types)?;
    let mut methods = String::new();
    for route in http["mappings"].as_array().ok_or("routes")? {
        let rpc = route["rpc"].as_str().ok_or("rpc")?;
        let (service, method) = rpc
            .strip_prefix("positron.v1.")
            .and_then(|v| v.split_once('/'))
            .ok_or("rpc")?;
        let service = service.strip_suffix("Service").ok_or("service")?;
        let mut name = service.to_owned();
        name.replace_range(..1, &service[..1].to_ascii_lowercase());
        let request = route["request"].as_str().ok_or("request")?;
        let response = route["response"].as_str().ok_or("response")?;
        writeln!(
            methods,
            " public Types.{response} {name}{method}(Types.{request} request, String bearer, java.time.Duration timeout) throws PositronException {{ return Codec.convert(call({rpc:?}, request, bearer, timeout), Types.{response}.class); }}"
        )?;
    }
    let client = fs::read_to_string(owner.join("java/Client.java"))?
        .replace("// GENERATED_METHODS", &methods);
    fs::write(java.join("Client.java"), client)?;
    for file in [
        "Codec.java",
        "Query.java",
        "BatchTracker.java",
        "PositronException.java",
    ] {
        fs::copy(owner.join("java").join(file), java.join(file))?;
    }
    fs::write(
        resources.join("contract.json"),
        serde_json::to_vec(
            &json!({"api_version":"positron.v1","schema_digest":digest,"schemas":schemas,"descriptor":descriptor,"routes":http["mappings"],"query_errors":errors}),
        )?,
    )?;
    fs::write(
        resources.join("release.json"),
        serde_json::to_vec_pretty(
            &json!({"group":"dev.positron","artifact":"sdk","version":env!("CARGO_PKG_VERSION"),"api_version":"positron.v1","schema_digest":digest,"release_manifest_surface":"SdkJava","registry":"https://repo.maven.apache.org/maven2","generator":"positron-api=1,java=21,maven=3.9.11,jackson=2.19.2,protoc-bin-vendored=3.2.0"}),
        )?,
    )?;
    for file in [
        "positron.proto",
        "schema.sha256",
        "http.json",
        "openapi.json",
        "query-golden-fixtures.json",
        "query-error-fixtures.json",
        "validation-fixtures.json",
    ] {
        fs::copy(
            root.join("api/positron/v1").join(file),
            resources.join("api").join(file),
        )?;
    }
    fs::copy(
        owner.join("java/dependencies.json"),
        resources.join("dependencies.json"),
    )?;
    fs::copy(root.join("sdk/java.md"), output.join("README.md"))?;
    fs::copy(root.join("LICENSE"), resources.join("LICENSE"))?;
    let pom = fs::read_to_string(owner.join("java/pom.xml"))?
        .replace("@VERSION@", env!("CARGO_PKG_VERSION"));
    fs::write(output.join("pom.xml"), pom)?;
    fs::create_dir_all(output.join("examples"))?;
    fs::copy(
        owner.join("java/Example.java"),
        output.join("examples/Example.java"),
    )?;
    Ok(())
}
